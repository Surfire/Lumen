import AppKit
import Combine
import ImageIO
import UniformTypeIdentifiers

@MainActor
final class ClipboardManager: ObservableObject {
    enum TemplateValidationResult: Equatable, Sendable {
        case valid(alias: String?)
        case emptyText
        case invalidAlias
        case reservedAlias(String)
    }

    static let internalType = NSPasteboard.PasteboardType("io.github.surfire.lumen.internal")
    nonisolated static let reservedTemplateAliases: Set<String> = ["qa", "tr", "translate", "img", "cb", "clip", "win"]
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.apple.is-sensitive"), internalType
    ]
    private static let sensitiveClipboardTypes = excludedTypes
        .subtracting([internalType])
        .union([.init("com.agilebits.onepassword")])
    private static let enabledKey = "clipboard.enabled"
    private static let limitKey = "clipboard.retentionCount"
    private static let thumbnailCacheLimit = 32
    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff,
        NSPasteboard.PasteboardType(UTType.jpeg.identifier),
        NSPasteboard.PasteboardType(UTType.heic.identifier),
        NSPasteboard.PasteboardType(UTType.webP.identifier),
    ]

    private enum CaptureOutcome: Sendable {
        case cancelled
        case unchanged
        case reloaded(items: [ClipboardItem], templates: [ClipboardItem])
        case upserted(ClipboardStore.UpsertResult)
    }

    private enum PinOutcome: Sendable {
        case unchanged
        case reloaded(items: [ClipboardItem], templates: [ClipboardItem])
        case toggled(id: Int64, pinned: Bool, evictedIDs: Set<Int64>, templates: [ClipboardItem])
    }

    private enum LimitOutcome: Sendable {
        case reloaded(items: [ClipboardItem], templates: [ClipboardItem])
        case pruned(Set<Int64>)
    }

    private enum TemplateSaveOutcome: Sendable {
        case rejected
        case saved(ClipboardStore.UpsertResult, templates: [ClipboardItem], reloadedItems: [ClipboardItem]?, isEdit: Bool)
    }

    @Published private(set) var enabled: Bool
    @Published private(set) var limit: Int
    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var templates: [ClipboardItem] = []
    @Published private(set) var failed = false
    let store: ClipboardStore
    private let storeQueue = DispatchQueue(label: "io.github.surfire.lumen.clipboard.store", qos: .userInitiated)
    private let defaults: UserDefaults
    private let pasteboard: NSPasteboard
    private let automaticPolling: Bool
    private let sessionCenter: NotificationCenter
    private let isConsoleSessionActive: () -> Bool
    private var sessionObservers: [AnyCancellable] = []
    private var sessionActive = false
    private var timer: Timer?
    private var lastChangeCount: Int?
    private var imageWork: Task<Void, Never>?
    private var loaded = false
    private var loadingHistory = false
    private var clearGeneration: UInt64 = 0
    private var templatesGeneration: UInt64 = 0
    private var thumbnailCache: [Int64: NSImage] = [:]
    private var thumbnailOrder: [Int64] = []

    init(defaults: UserDefaults, pasteboard: NSPasteboard, directory: URL = ClipboardStore.defaultDirectory,
         automaticPolling: Bool = true, sessionCenter: NotificationCenter = NSWorkspace.shared.notificationCenter,
         isConsoleSessionActive: @escaping () -> Bool = ClipboardManager.isOnConsole) {
        self.isConsoleSessionActive = isConsoleSessionActive
        self.defaults = defaults
        self.pasteboard = pasteboard
        self.automaticPolling = automaticPolling
        self.sessionCenter = sessionCenter
        enabled = defaults.bool(forKey: Self.enabledKey)
        let limit = defaults.object(forKey: Self.limitKey) as? Int ?? ClipboardStore.defaultLimit
        self.limit = ClipboardStore.boundedLimit(limit)
        store = ClipboardStore(directory: directory, limit: limit)
        loadTemplates()
    }

    nonisolated static func isOnConsole() -> Bool {
        let session = CGSessionCopyCurrentDictionary() as? [String: Any]
        return session?["kCGSSessionOnConsoleKey"] as? Bool == true
    }

    deinit {
        timer?.invalidate()
        imageWork?.cancel()
    }

    func start() {
        guard sessionObservers.isEmpty else { return }
        sessionObservers = [
            observeSession(NSWorkspace.sessionDidResignActiveNotification, active: false),
            observeSession(NSWorkspace.sessionDidBecomeActiveNotification, active: true)
        ]
        // Sample only once the observers can see subsequent session transitions.
        sessionActive = isConsoleSessionActive()
        configurePolling()
    }

    func stop() {
        sessionObservers.removeAll()
        pausePolling()
    }

    func setEnabled(_ value: Bool) {
        guard enabled != value else { return }
        defaults.set(value, forKey: Self.enabledKey)
        enabled = value
        configurePolling()
    }

    func setLimit(_ value: Int) {
        let next = ClipboardStore.boundedLimit(value)
        let store = self.store
        let expectedGeneration = self.clearGeneration
        let needsFullLoad = !self.loaded || self.failed
        performStoreWork({ () throws -> LimitOutcome in
            let evicted = try store.setLimitReturningEvicted(next)
            return needsFullLoad
                ? .reloaded(items: try store.items(), templates: try store.templateItems())
                : .pruned(evicted)
        }) { manager, result in
            switch result {
            case .success(let outcome):
                manager.defaults.set(next, forKey: Self.limitKey)
                manager.limit = next
                guard manager.clearGeneration == expectedGeneration else { return }
                manager.templatesGeneration &+= 1
                switch outcome {
                case .reloaded(let records, let templates):
                    if manager.items != records { manager.items = records }
                    if manager.templates != templates { manager.templates = templates }
                case .pruned(let evictedIDs):
                    if !evictedIDs.isEmpty {
                        manager.items.removeAll { evictedIDs.contains($0.id) }
                        manager.templates.removeAll { evictedIDs.contains($0.id) }
                        manager.evictThumbnails(ids: evictedIDs)
                    }
                }
                if manager.failed { manager.failed = false }
                manager.loaded = true
            case .failure:
                manager.failed = true
            }
        }
    }

    func loadTemplates() {
        let store = self.store
        let expectedGeneration = self.clearGeneration
        let expectedTemplates = self.templatesGeneration
        performStoreWork({ try store.templateItems() }) { manager, result in
            guard manager.clearGeneration == expectedGeneration,
                  manager.templatesGeneration == expectedTemplates else { return }
            if case .success(let records) = result, manager.templates != records {
                manager.templates = records
            }
        }
    }

    func loadHistory() {
        guard (!loaded || failed), !loadingHistory else { return }
        loadingHistory = true
        let store = self.store
        let expectedGeneration = self.clearGeneration
        performStoreWork({ () throws -> (items: [ClipboardItem], templates: [ClipboardItem]) in
            (try store.items(), try store.templateItems())
        }) { manager, result in
            manager.loadingHistory = false
            guard manager.clearGeneration == expectedGeneration else { return }
            switch result {
            case .success(let records):
                manager.templatesGeneration &+= 1
                if manager.items != records.items { manager.items = records.items }
                if manager.templates != records.templates { manager.templates = records.templates }
                if manager.failed { manager.failed = false }
                manager.loaded = true
            case .failure:
                manager.failed = true
            }
        }
    }

    func togglePin(id: Int64) {
        let store = self.store
        let expectedGeneration = self.clearGeneration
        let needsFullLoad = !self.loaded || self.failed
        performStoreWork({ () throws -> PinOutcome in
            let toggled = try store.togglePinReturningEvicted(id: id)
            let templates = try store.templateItems()
            if needsFullLoad { return .reloaded(items: try store.items(), templates: templates) }
            guard let toggled else { return .unchanged }
            return .toggled(id: id, pinned: toggled.pinned, evictedIDs: toggled.evictedIDs, templates: templates)
        }) { manager, result in
            guard manager.clearGeneration == expectedGeneration else { return }
            switch result {
            case .success(.unchanged):
                if manager.failed { manager.failed = false }
                manager.loaded = true
            case .success(.reloaded(let records, let templates)):
                manager.templatesGeneration &+= 1
                if manager.items != records { manager.items = records }
                if manager.templates != templates { manager.templates = templates }
                if manager.failed { manager.failed = false }
                manager.loaded = true
            case .success(.toggled(let id, let pinned, let evictedIDs, let templates)):
                manager.templatesGeneration &+= 1
                var next = manager.items
                if let index = next.firstIndex(where: { $0.id == id }) {
                    next[index] = next[index].withPinned(pinned)
                }
                if !evictedIDs.isEmpty {
                    next.removeAll { evictedIDs.contains($0.id) }
                    manager.evictThumbnails(ids: evictedIDs)
                }
                if next != manager.items { manager.items = next }
                if manager.templates != templates { manager.templates = templates }
                if manager.failed { manager.failed = false }
                manager.loaded = true
            case .failure:
                manager.failed = true
            }
        }
    }

    func remove(id: Int64) {
        let store = self.store
        let expectedGeneration = self.clearGeneration
        let needsFullLoad = !self.loaded || self.failed
        performStoreWork({ () throws -> (items: [ClipboardItem]?, templates: [ClipboardItem]) in
            try store.remove(id: id)
            return (needsFullLoad ? try store.items() : nil, try store.templateItems())
        }) { manager, result in
            guard manager.clearGeneration == expectedGeneration else { return }
            switch result {
            case .success(let payload):
                manager.templatesGeneration &+= 1
                if let records = payload.items {
                    if manager.items != records { manager.items = records }
                    manager.loaded = true
                } else {
                    if manager.items.contains(where: { $0.id == id }) {
                        manager.items.removeAll { $0.id == id }
                    }
                    manager.loaded = true
                }
                if manager.templates != payload.templates { manager.templates = payload.templates }
                manager.evictThumbnails(ids: [id])
                if manager.failed { manager.failed = false }
            case .failure:
                manager.failed = true
            }
        }
    }

    func clearAll() {
        imageWork?.cancel()
        imageWork = nil
        clearGeneration &+= 1
        templatesGeneration &+= 1
        if lastChangeCount != nil { lastChangeCount = pasteboard.changeCount }
        let store = self.store
        performStoreWork({ try store.clearAll() }) { manager, result in
            switch result {
            case .success:
                if !manager.items.isEmpty { manager.items = [] }
                if !manager.templates.isEmpty { manager.templates = [] }
                manager.clearThumbnailCache()
                if manager.failed { manager.failed = false }
                manager.loaded = true
            case .failure:
                manager.failed = true
            }
        }
    }

    func thumbnail(id: Int64) -> NSImage? {
        if let cached = thumbnailCache[id] {
            touchThumbnailOrder(id: id)
            return cached
        }
        guard let image = (try? store.thumbnail(id: id)).flatMap(NSImage.init(data:)) else { return nil }
        if items.contains(where: { $0.id == id }) { cacheThumbnail(image, for: id) }
        return image
    }

    func loadThumbnail(id: Int64) async -> NSImage? {
        if let cached = thumbnailCache[id] {
            touchThumbnailOrder(id: id)
            return cached
        }
        let store = self.store
        let decoded: CGImage? = await Task.detached(priority: .utility) {
            guard !Task.isCancelled, let data = try? store.thumbnail(id: id),
                  let source = ClipboardStore.imageSource(data) else { return nil }
            return CGImageSourceCreateImageAtIndex(source, 0, [
                kCGImageSourceShouldCacheImmediately: true
            ] as CFDictionary)
        }.value
        guard !Task.isCancelled, let cgImage = decoded else { return nil }
        let image = NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
        if items.contains(where: { $0.id == id }) { cacheThumbnail(image, for: id) }
        return image
    }

    nonisolated static func validateTemplate(text: String, alias: String?) -> TemplateValidationResult {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .emptyText }
        guard let alias else { return .valid(alias: nil) }
        if alias.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .valid(alias: nil) }
        guard let normalized = ClipboardStore.normalizedAlias(alias) else { return .invalidAlias }
        if reservedTemplateAliases.contains(normalized) { return .reservedAlias(normalized) }
        return .valid(alias: normalized)
    }

    func saveTemplate(id: Int64?, text: String, alias: String?, pinned: Bool, completion: ((Bool) -> Void)? = nil) {
        guard case .valid(let resolvedAlias) = Self.validateTemplate(text: text, alias: alias) else {
            completion?(false)
            return
        }
        let store = self.store
        let expectedGeneration = self.clearGeneration
        let needsFullLoad = !self.loaded || self.failed
        performStoreWork({ () throws -> TemplateSaveOutcome in
            let upserted: ClipboardStore.UpsertResult?
            if let id {
                upserted = try store.updateTemplate(id: id, text: text, alias: resolvedAlias, pinned: pinned)
            } else {
                upserted = try store.createTemplate(text: text, alias: resolvedAlias, pinned: pinned, capturedAt: .now)
            }
            guard let upserted else { return .rejected }
            let templates = try store.templateItems()
            let reloadedItems = needsFullLoad ? try store.items() : nil
            return .saved(upserted, templates: templates, reloadedItems: reloadedItems, isEdit: id != nil)
        }) { manager, result in
            guard manager.clearGeneration == expectedGeneration else {
                completion?(false)
                return
            }
            switch result {
            case .success(.rejected):
                completion?(false)
            case .success(.saved(let upserted, let templates, let reloadedItems, let isEdit)):
                manager.templatesGeneration &+= 1
                if let reloadedItems {
                    if manager.items != reloadedItems { manager.items = reloadedItems }
                    manager.loaded = true
                } else {
                    var next = manager.items
                    next.removeAll { upserted.evictedIDs.contains($0.id) }
                    if isEdit, let index = next.firstIndex(where: { $0.id == upserted.item.id }) {
                        if upserted.evictedIDs.contains(upserted.item.id) {
                            next.remove(at: index)
                        } else {
                            next[index] = upserted.item
                        }
                    } else if !upserted.evictedIDs.contains(upserted.item.id) {
                        next.removeAll { $0.id == upserted.item.id }
                        next.insert(upserted.item, at: 0)
                    }
                    if manager.items != next { manager.items = next }
                }
                if manager.templates != templates { manager.templates = templates }
                manager.evictThumbnails(ids: upserted.evictedIDs)
                if manager.failed { manager.failed = false }
                completion?(true)
            case .failure:
                manager.failed = true
                completion?(false)
            }
        }
    }

    func matchingTemplates(for query: String) -> [(item: ClipboardItem, score: Int)] {
        let term = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !term.isEmpty else { return [] }
        return templates.compactMap { item -> (item: ClipboardItem, score: Int)? in
            guard let alias = item.alias?.lowercased(), !alias.isEmpty else { return nil }
            let score: Int
            if alias == term {
                score = 108
            } else if term.count >= 2 && alias.hasPrefix(term) {
                score = 82
            } else if term.count >= 2 && alias.contains(term) {
                score = 60
            } else {
                return nil
            }
            return (item, score)
        }
        .sorted { $0.score > $1.score }
    }

    func currentPasteboardPreviewText() -> String? {
        readablePasteboardString()
    }

    private func readablePasteboardString() -> String? {
        guard let types = pasteboard.types,
              Self.sensitiveClipboardTypes.isDisjoint(with: types),
              types.contains(.string) else { return nil }
        return pasteboard.string(forType: .string)
    }

    @discardableResult static func writeInternalString(_ text: String, to pasteboard: NSPasteboard = .general) -> Bool {
        let item = NSPasteboardItem()
        return item.setString(text, forType: .string) && writeInternalItem(item, to: pasteboard)
    }

    @discardableResult static func writeInternalFileURL(_ url: URL, to pasteboard: NSPasteboard = .general) -> Bool {
        guard url.isFileURL else { return false }
        let item = NSPasteboardItem()
        return item.setString(url.absoluteString, forType: .fileURL) && writeInternalItem(item, to: pasteboard)
    }

    private static func writeInternalItem(_ item: NSPasteboardItem, to pasteboard: NSPasteboard) -> Bool {
        guard item.setData(Data(), forType: internalType) else { return false }
        pasteboard.clearContents()
        return pasteboard.writeObjects([item])
    }

    @discardableResult func copyExpanded(_ item: ClipboardItem, liveClipboardText: String? = nil, now: Date = .now) -> String? {
        guard let rawText = item.text else { return nil }
        let clipboardText = liveClipboardText ?? readablePasteboardString()
        let expanded = ClipboardTemplateExpander.expand(rawText, clipboardText: clipboardText, now: now)
        guard Self.writeInternalString(expanded, to: pasteboard) else {
            failed = true
            return nil
        }
        noteItemUsed(id: item.id)
        return expanded
    }

    @discardableResult func copy(id: Int64) -> Bool {
        guard let entry = items.first(where: { $0.id == id }) ?? templates.first(where: { $0.id == id }) else { return false }
        do {
            let store = self.store
            let wrote: Bool
            if let text = entry.text {
                if entry.hasAlias || ClipboardTemplateExpander.containsVariables(text) {
                    return copyExpanded(entry) != nil
                }
                wrote = Self.writeInternalString(text, to: pasteboard)
            } else if let path = entry.filePath {
                // A real file reference, so Cmd+V pastes the file itself. Nothing is read or downloaded here.
                wrote = Self.writeInternalFileURL(URL(fileURLWithPath: path), to: pasteboard)
            } else if let data = try storeQueue.sync(execute: { try store.image(id: id) }) {
                let item = NSPasteboardItem()
                wrote = item.setData(data, forType: .png) && Self.writeInternalItem(item, to: pasteboard)
            } else { return false }
            guard wrote else { failed = true; return false }
            noteItemUsed(id: id)
            return true
        } catch {
            failed = true
            return false
        }
    }

    private func noteItemUsed(id: Int64) {
        moveItemToFront(id: id)
        let store = self.store
        let expectedGeneration = self.clearGeneration
        performStoreWork({ try store.noteUsed(id: id) }) { manager, result in
            guard manager.clearGeneration == expectedGeneration else { return }
            switch result {
            case .success:
                manager.moveItemToFront(id: id)
                if manager.failed { manager.failed = false }
            case .failure:
                manager.failed = true
            }
        }
    }

    private func observeSession(_ name: Notification.Name, active: Bool) -> AnyCancellable {
        let center = sessionCenter
        let observer = center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self else { return }
                self.sessionActive = active
                self.configurePolling()
            }
        }
        return AnyCancellable { center.removeObserver(observer) }
    }

    private func configurePolling() {
        pausePolling()
        guard enabled, sessionActive, !sessionObservers.isEmpty else { return }
        // Don't record whatever was already on the board before opt-in or during an inactive session.
        lastChangeCount = pasteboard.changeCount
        guard automaticPolling else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { _ = self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func pausePolling() {
        timer?.invalidate()
        timer = nil
        lastChangeCount = nil
        imageWork?.cancel()
    }

    // One production poll tick; GUI smoke drives it directly against a named pasteboard.
    @discardableResult func poll() -> Task<Void, Never>? {
        guard let lastChangeCount else { return nil }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return nil }
        self.lastChangeCount = count
        imageWork?.cancel()
        // NSPasteboard.types is the union of the types of all items on the board.
        guard let types = pasteboard.types, Self.excludedTypes.isDisjoint(with: types),
              pasteboard.changeCount == count else { return nil }
        let capturedAt = Date.now
        // macOS doesn't expose the writer on NSPasteboard. The foreground app is a best-effort attribution.
        let source = NSWorkspace.shared.frontmostApplication
        let bundleID = source?.bundleIdentifier
        let appName = source?.localizedName
        // Copied files win over the icon/preview bitmaps that Finder places beside them.
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let fileURL = urls.first(where: { !store.contains($0) }), pasteboard.changeCount == count {
            let path = fileURL.path
            let store = self.store
            let expectedGeneration = self.clearGeneration
            let needsFullLoad = !self.loaded || self.failed
            performStoreWork({ () throws -> CaptureOutcome in
                guard let upserted = try store.upsertFile(path, capturedAt: capturedAt, bundleID: bundleID, appName: appName) else {
                    return .unchanged
                }
                return needsFullLoad
                    ? .reloaded(items: try store.items(), templates: try store.templateItems())
                    : .upserted(upserted)
            }) { manager, result in
                guard manager.clearGeneration == expectedGeneration else { return }
                manager.applyCaptureResult(result)
            }
            return nil
        }
        let imageType = Self.imageTypes.first { types.contains($0) }
        if let imageType, let bytes = pasteboard.data(forType: imageType) {
            guard pasteboard.changeCount == count else { return nil }
            let store = self.store
            let queue = self.storeQueue
            let expectedGeneration = self.clearGeneration
            let needsFullLoad = !self.loaded || self.failed
            let work = Task.detached(priority: .utility) { [weak self] in
                guard let image = Self.encodeImage(bytes), !Task.isCancelled else { return }
                let result: Result<CaptureOutcome, Error> = await withCheckedContinuation { continuation in
                    queue.async {
                        guard !Task.isCancelled else {
                            continuation.resume(returning: .success(.cancelled))
                            return
                        }
                        let outcome = Result<CaptureOutcome, Error> {
                            guard let upserted = try store.upsertImage(image.png, thumbnail: image.thumbnail,
                                                                       capturedAt: capturedAt, bundleID: bundleID, appName: appName) else {
                                return .unchanged
                            }
                            return needsFullLoad
                                ? .reloaded(items: try store.items(), templates: try store.templateItems())
                                : .upserted(upserted)
                        }
                        continuation.resume(returning: outcome)
                    }
                }
                guard !Task.isCancelled else { return }
                await MainActor.run { [weak self] in
                    guard let self, self.clearGeneration == expectedGeneration, !Task.isCancelled else { return }
                    self.applyCaptureResult(result)
                }
            }
            imageWork = work
            return work
        }
        if types.contains(.string), let text = pasteboard.string(forType: .string), pasteboard.changeCount == count {
            let store = self.store
            let expectedGeneration = self.clearGeneration
            let needsFullLoad = !self.loaded || self.failed
            performStoreWork({ () throws -> CaptureOutcome in
                guard let upserted = try store.upsertText(text, capturedAt: capturedAt, bundleID: bundleID, appName: appName) else {
                    return .unchanged
                }
                return needsFullLoad
                    ? .reloaded(items: try store.items(), templates: try store.templateItems())
                    : .upserted(upserted)
            }) { manager, result in
                guard manager.clearGeneration == expectedGeneration else { return }
                manager.applyCaptureResult(result)
            }
        }
        return nil
    }

    private func performStoreWork<T: Sendable>(
        _ work: @escaping @Sendable () throws -> T,
        apply: @escaping @MainActor (ClipboardManager, Result<T, Error>) -> Void
    ) {
        if automaticPolling {
            storeQueue.async { [weak self] in
                let result = Result(catching: work)
                DispatchQueue.main.async { [weak self] in
                    MainActor.assumeIsolated {
                        guard let self else { return }
                        apply(self, result)
                    }
                }
            }
        } else {
            let result = storeQueue.sync { Result(catching: work) }
            apply(self, result)
        }
    }

    private func applyCaptureResult(_ result: Result<CaptureOutcome, Error>) {
        switch result {
        case .success(.cancelled), .success(.unchanged):
            break
        case .success(.reloaded(let records, let templates)):
            templatesGeneration &+= 1
            if items != records { items = records }
            if self.templates != templates { self.templates = templates }
            if failed { failed = false }
            loaded = true
        case .success(.upserted(let upserted)):
            templatesGeneration &+= 1
            var next = items
            next.removeAll { $0.id == upserted.item.id || upserted.evictedIDs.contains($0.id) }
            next.insert(upserted.item, at: 0)
            items = next
            var nextTemplates = templates
            nextTemplates.removeAll { $0.id == upserted.item.id || upserted.evictedIDs.contains($0.id) }
            if upserted.item.hasAlias {
                let insertAt = upserted.item.pinned ? 0 : (nextTemplates.firstIndex { !$0.pinned } ?? nextTemplates.endIndex)
                nextTemplates.insert(upserted.item, at: insertAt)
            }
            if templates != nextTemplates { templates = nextTemplates }
            evictThumbnails(ids: upserted.evictedIDs)
            if failed { failed = false }
            loaded = true
        case .failure:
            failed = true
        }
    }

    private func moveItemToFront(id: Int64) {
        if let index = items.firstIndex(where: { $0.id == id }), index > 0 {
            var next = items
            let entry = next.remove(at: index)
            next.insert(entry, at: 0)
            items = next
        }
        if let templateIndex = templates.firstIndex(where: { $0.id == id }) {
            var nextTemplates = templates
            let entry = nextTemplates.remove(at: templateIndex)
            let targetIndex = entry.pinned ? 0 : (nextTemplates.firstIndex { !$0.pinned } ?? nextTemplates.endIndex)
            nextTemplates.insert(entry, at: targetIndex)
            if nextTemplates != templates { templates = nextTemplates }
        }
    }

    private func cacheThumbnail(_ image: NSImage, for id: Int64) {
        thumbnailCache[id] = image
        touchThumbnailOrder(id: id)
        while thumbnailOrder.count > Self.thumbnailCacheLimit {
            let oldest = thumbnailOrder.removeFirst()
            thumbnailCache.removeValue(forKey: oldest)
        }
    }

    private func touchThumbnailOrder(id: Int64) {
        if let index = thumbnailOrder.firstIndex(of: id) { thumbnailOrder.remove(at: index) }
        thumbnailOrder.append(id)
    }

    private func evictThumbnails(ids: Set<Int64>) {
        guard !ids.isEmpty else { return }
        for id in ids { thumbnailCache.removeValue(forKey: id) }
        thumbnailOrder.removeAll { ids.contains($0) }
    }

    private func clearThumbnailCache() {
        thumbnailCache.removeAll()
        thumbnailOrder.removeAll()
    }

    nonisolated private static func encodeImage(_ bytes: Data) -> (png: Data, thumbnail: Data)? {
        guard let source = ClipboardStore.imageSource(bytes) else { return nil }
        func png(maximumDimension: Int) -> Data? {
            guard !Task.isCancelled, let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: maximumDimension
            ] as CFDictionary) else { return nil }
            let data = NSMutableData()
            guard let output = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
            CGImageDestinationAddImage(output, image, nil)
            return CGImageDestinationFinalize(output) ? data as Data : nil
        }
        if CGImageSourceGetType(source) == UTType.png.identifier as CFString {
            // Do not fall back to decoding an invalid or oversized PNG during re-encoding.
            guard ClipboardStore.isDecodablePNG(source) else { return nil }
            // Keep a bounded PNG verbatim, including its original dimensions and metadata.
            if bytes.count <= ClipboardStore.maximumImageBytes {
                return png(maximumDimension: 240).map { (bytes, $0) }
            }
        }
        // Other inline image bytes (never file URLs) are resized and re-encoded to fit.
        for dimension in [1600, 896, 512, 320] {
            if let payload = png(maximumDimension: dimension), payload.count <= ClipboardStore.maximumImageBytes {
                return png(maximumDimension: 240).map { (payload, $0) }
            }
        }
        return nil
    }
